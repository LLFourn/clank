//! Deterministic cargo-about JSON rendering, including each crate's NOTICE.
use anyhow::{Context, Result, ensure};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";
type Key = (String, String);

fn field<'a>(v: &'a Value, name: &str) -> Result<&'a str> {
    v[name]
        .as_str()
        .with_context(|| format!("missing string field {name}"))
}

fn key(p: &Value) -> Result<Key> {
    Ok((field(p, "name")?.into(), field(p, "version")?.into()))
}

/// Cargo gives all path dependencies a null source; only actual workspace
/// package IDs may be omitted, never arbitrary paths or matching names.
pub fn third_party(about: &Value, workspace: &BTreeSet<String>) -> Result<BTreeMap<Key, Value>> {
    let mut packages = BTreeMap::new();
    for c in about["crates"].as_array().context("missing crates")? {
        let p = &c["package"];
        let (name, version) = key(p)?;
        if p["source"].is_null() {
            if workspace.contains(field(p, "id")?) {
                continue;
            }
            anyhow::bail!(
                "{name} {version} is a path dependency outside the workspace: publish it, depend on a registry version, or give it a notice here"
            );
        }
        ensure!(
            p["source"] == CRATES_IO,
            "{name} {version} is not from crates.io: {}",
            p["source"]
        );
        packages.insert((name, version), p.clone());
    }
    Ok(packages)
}

fn wrapped(label: &str, items: &[String]) -> String {
    let mut out = label.to_owned();
    let mut width = label.chars().count();
    for (i, item) in items.iter().enumerate() {
        let item = format!("{item}{}", if i + 1 < items.len() { "," } else { "" });
        let len = item.chars().count();
        if i != 0 {
            if width + 1 + len > 78 {
                out.push('\n');
                out.push_str(&" ".repeat(label.len()));
                width = label.len();
            } else {
                out.push(' ');
                width += 1;
            }
        }
        out.push_str(&item);
        width += len;
    }
    out
}

pub fn render(
    about: &Value,
    workspace: &BTreeSet<String>,
    version: &str,
    targets: &[String],
) -> Result<String> {
    let packages = third_party(about, workspace)?;
    let mut texts: BTreeMap<Key, (String, BTreeSet<Key>)> = BTreeMap::new();
    for lic in about["licenses"].as_array().context("missing licenses")? {
        let entry = texts
            .entry((field(lic, "id")?.into(), field(lic, "text")?.into()))
            .or_insert_with(|| {
                (
                    lic["name"].as_str().unwrap_or_default().into(),
                    BTreeSet::new(),
                )
            });
        for used in lic["used_by"].as_array().context("missing used_by")? {
            let k = key(&used["crate"])?;
            if packages.contains_key(&k) {
                entry.1.insert(k);
            }
        }
    }
    texts.retain(|_, (_, users)| !users.is_empty());
    let mut uses: BTreeMap<Key, Vec<(usize, String)>> = BTreeMap::new();
    for (i, ((id, _), (_, users))) in texts.iter().enumerate() {
        for k in users {
            uses.entry(k.clone()).or_default().push((i + 1, id.clone()));
        }
    }
    let mut out: Vec<String> = [
        "Third-party Rust dependencies of clank",
        "======================================",
        "",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect();
    out.push(format!(
        "Generated by scripts/notices/generate.sh with cargo-about {version}"
    ));
    out.extend(
        [
            "from Cargo.lock. Do not edit: scripts/notices/check.sh fails on any",
            "difference. Covers the normal dependencies (no dev or build",
            "dependencies) built for:",
            "",
        ]
        .into_iter()
        .map(str::to_owned),
    );
    out.extend(targets.iter().map(|t| format!("  {t}")));
    out.push(String::new());
    out.push(format!(
        "{} packages. Each entry gives the licence the crate declares,",
        packages.len()
    ));
    out.extend(
        [
            "the licence clank uses it under (the chosen branch of an OR, every part",
            "of an AND), and the numbered licence texts below that apply to it, which",
            "carry the crate's own copyright lines where its licence files do.",
            "",
            "",
            "Packages",
            "--------",
        ]
        .into_iter()
        .map(str::to_owned),
    );
    let mut noticed = Vec::new();
    for ((name, version), p) in &packages {
        let used = uses
            .get(&(name.clone(), version.clone()))
            .with_context(|| format!("{name} {version} has no licence text"))?;
        let ids: BTreeSet<_> = used.iter().map(|(_, id)| id.as_str()).collect();
        out.extend([
            String::new(),
            format!("{name} {version}"),
            format!("  source:     https://crates.io/crates/{name}/{version}"),
            format!("  declared:   {}", field(p, "license")?),
            format!(
                "  used under: {}",
                ids.iter().copied().collect::<Vec<_>>().join(" AND ")
            ),
            wrapped(
                "  texts:      ",
                &used
                    .iter()
                    .map(|(n, id)| format!("[{n}] {id}"))
                    .collect::<Vec<_>>(),
            ),
        ]);
        if ids.contains("MPL-2.0") {
            out.push(format!("  Source Code Form (MPL-2.0 section 3.2): https://crates.io/api/v1/crates/{name}/{version}/download"));
        }
        let root = Path::new(field(p, "manifest_path")?)
            .parent()
            .context("manifest has no parent")?;
        let mut entries = std::fs::read_dir(root)?.collect::<std::io::Result<Vec<_>>>()?;
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let file = e.file_name().to_string_lossy().into_owned();
            if file.to_ascii_uppercase().contains("NOTICE") && e.path().is_file() {
                out.push(format!("  notice:     {file} (under Notices below)"));
                noticed.push((
                    format!("{name} {version}: {file}"),
                    std::fs::read_to_string(e.path())?,
                ));
            }
        }
    }
    out.extend(
        ["", "", "Licence texts", "-------------"]
            .into_iter()
            .map(str::to_owned),
    );
    for (i, ((id, text), (name, users))) in texts.iter().enumerate() {
        out.extend([
            String::new(),
            format!("[{}] {id}: {name}", i + 1),
            wrapped(
                "Used by: ",
                &users
                    .iter()
                    .map(|(name, version)| format!("{name} {version}"))
                    .collect::<Vec<_>>(),
            ),
            String::new(),
            text.trim_end().to_owned(),
            String::new(),
            "-".repeat(78),
        ]);
    }
    if !noticed.is_empty() {
        out.extend(
            ["", "", "Notices", "-------"]
                .into_iter()
                .map(str::to_owned),
        );
        for (name, body) in noticed {
            out.extend([
                String::new(),
                name,
                String::new(),
                body.trim_end().to_owned(),
                String::new(),
                "-".repeat(78),
            ]);
        }
    }
    Ok(out.join("\n") + "\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn only_workspace_package_ids_are_omitted() {
        let workspace = BTreeSet::from(["path+file:///ours#clank@0.1.0".into()]);
        let ours = json!({"package":{"name":"clank","version":"0.1.0","source":null,"id":workspace.first().unwrap()}});
        let registry = json!({"package":{"name":"tokio","version":"1.0.0","source":CRATES_IO}});
        assert_eq!(
            third_party(&json!({"crates":[ours, registry]}), &workspace)
                .unwrap()
                .len(),
            1
        );
        for name in ["clank", "outside"] {
            let bad = json!({"crates":[{"package":{"name":name,"version":"0.1.0","source":null,"id":"path+file:///elsewhere#clank@0.1.0"}}]});
            assert!(
                third_party(&bad, &workspace)
                    .unwrap_err()
                    .to_string()
                    .contains("path dependency outside")
            );
        }
    }

    #[test]
    fn notices_and_source_offers_survive_grouping_and_output_is_stable() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("NOTICE.txt"), "Copyright holder\n").unwrap();
        let p = json!({"name":"example","version":"1.0.0","source":CRATES_IO,"license":"MPL-2.0", "manifest_path":dir.path().join("Cargo.toml")});
        let lic = json!({"id":"MPL-2.0","name":"Mozilla Public License 2.0","text":"License body\n", "used_by":[{"crate":p}]});
        let about = json!({"crates":[{"package":p}],"licenses":[lic.clone(),lic]});
        let output = render(&about, &BTreeSet::new(), "0.1", &["target".into()]).unwrap();
        assert_eq!(
            output,
            render(&about, &BTreeSet::new(), "0.1", &["target".into()]).unwrap()
        );
        assert!(output.contains("Source Code Form (MPL-2.0 section 3.2): https://crates.io/api/v1/crates/example/1.0.0/download"));
        assert_eq!(output.matches("[1] MPL-2.0: Mozilla").count(), 1);
        assert!(output.contains("example 1.0.0: NOTICE.txt\n\nCopyright holder"));
        let mut missing = about;
        missing["licenses"] = json!([]);
        assert!(
            render(&missing, &BTreeSet::new(), "0.1", &[])
                .unwrap_err()
                .to_string()
                .contains("no licence text")
        );
    }
}
