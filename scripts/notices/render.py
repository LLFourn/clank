"""Render cargo-about's JSON as clank's Rust dependency notice.

A cargo-about template cannot read a crate's NOTICE file, so the JSON
is rendered here instead. Reads the JSON on stdin, writes the notice to
stdout. Nothing machine-local (paths, times) reaches the output, so two
runs over the same Cargo.lock are byte-identical.
"""

import json
import os
import re
import sys
import textwrap

CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"
NOTICE_FILE = re.compile(r"NOTICE", re.IGNORECASE)
# MPL-2.0 section 3.2: whoever distributes the Executable Form must say
# where the Source Code Form is available.
SOURCE_OFFER = {"MPL-2.0"}


def key(package):
    return (package["name"], package["version"])


def source_url(package):
    if package["source"] != CRATES_IO:
        sys.exit(f"{package['name']} {package['version']} is not from crates.io: {package['source']}")
    return f"https://crates.io/crates/{package['name']}/{package['version']}"


def download_url(package):
    return f"https://crates.io/api/v1/crates/{package['name']}/{package['version']}/download"


def notices(package):
    root = os.path.dirname(package["manifest_path"])
    found = []
    for name in sorted(os.listdir(root)):
        path = os.path.join(root, name)
        if NOTICE_FILE.search(name) and os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                found.append((name, f.read()))
    return found


def wrapped(label, items):
    # NO-BREAK SPACE holds each item together: textwrap breaks only at
    # ASCII whitespace.
    return textwrap.fill(
        ", ".join(i.replace(" ", "\u00a0") for i in items),
        width=78,
        initial_indent=label,
        subsequent_indent=" " * len(label),
        break_on_hyphens=False,
        break_long_words=False,
    ).replace("\u00a0", " ")


def third_party(about, workspace):
    """Every package but the workspace's own, refusing a path dependency
    we cannot name a source for: Cargo reports source=null for any path
    or patched crate, not only for workspace members. `workspace` holds
    Cargo package ids, since a path dependency may share a member's
    name."""
    packages = {}
    for c in about["crates"]:
        package = c["package"]
        if package["source"] is None:
            if package["id"] in workspace:
                continue
            sys.exit(
                f"{package['name']} {package['version']} is a path dependency outside the "
                "workspace: publish it, depend on a registry version, or give it a notice here"
            )
        packages[key(package)] = package
    return packages


def main():
    about = json.load(sys.stdin)
    version = sys.argv[1]
    workspace = set(os.environ["CLANK_WORKSPACE_MEMBERS"].splitlines())
    targets = sys.argv[2:]

    packages = third_party(about, workspace)
    by_text = {}
    for lic in about["licenses"]:
        users = {key(u["crate"]) for u in lic["used_by"]} & packages.keys()
        by_text.setdefault((lic["id"], lic["text"]), (lic, set()))[1].update(users)
    texts = [(lic, sorted(by)) for _, (lic, by) in sorted(by_text.items()) if by]
    uses = {k: [] for k in packages}
    for number, (lic, by) in enumerate(texts, 1):
        for k in by:
            uses[k].append((number, lic["id"]))

    out = []
    w = out.append
    w("Third-party Rust dependencies of clank")
    w("======================================")
    w("")
    w(f"Generated by scripts/notices/generate.sh with cargo-about {version}")
    w("from Cargo.lock. Do not edit: scripts/notices/check.sh fails on any")
    w("difference. Covers the normal dependencies (no dev or build")
    w("dependencies) built for:")
    w("")
    for t in targets:
        w(f"  {t}")
    w("")
    w(f"{len(packages)} packages. Each entry gives the licence the crate declares,")
    w("the licence clank uses it under (the chosen branch of an OR, every part")
    w("of an AND), and the numbered licence texts below that apply to it, which")
    w("carry the crate's own copyright lines where its licence files do.")
    w("")
    w("")
    w("Packages")
    w("--------")
    noticed = []
    for k in sorted(packages):
        p = packages[k]
        used = uses[k]
        if not used:
            sys.exit(f"{p['name']} {p['version']} has no licence text")
        ids = sorted({i for _, i in used})
        w("")
        w(f"{p['name']} {p['version']}")
        w(f"  source:     {source_url(p)}")
        w(f"  declared:   {p['license']}")
        w(f"  used under: {' AND '.join(ids)}")
        w(wrapped("  texts:      ", [f"[{n}] {i}" for n, i in used]))
        for i in ids:
            if i in SOURCE_OFFER:
                w(f"  Source Code Form ({i} section 3.2): {download_url(p)}")
        for name, body in notices(p):
            w(f"  notice:     {name} (under Notices below)")
            noticed.append((p, name, body))
    w("")
    w("")
    w("Licence texts")
    w("-------------")
    for n, (lic, by) in enumerate(texts, 1):
        w("")
        w(f"[{n}] {lic['id']}: {lic['name']}")
        w(wrapped("Used by: ", [f"{name} {v}" for name, v in by]))
        w("")
        w(lic["text"].rstrip())
        w("")
        w("-" * 78)
    if noticed:
        w("")
        w("")
        w("Notices")
        w("-------")
        for p, name, body in noticed:
            w("")
            w(f"{p['name']} {p['version']}: {name}")
            w("")
            w(body.rstrip())
            w("")
            w("-" * 78)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
